import assert from 'node:assert/strict';
import { QualityGovernor, QUALITY_BUDGETS } from '../src/quality.js';
const g = new QualityGovernor();
for (let i = 0; i < 89; i++) g.sample(33.3);
assert.equal(g.level, 'high', 'one incomplete window must not downgrade');
g.sample(33.3);
assert.equal(g.level, 'balanced', 'sustained slow frames drop one level');
for (let i = 0; i < 100; i++) g.sample(33.3);
assert.equal(g.level, 'low', 'sustained load reaches the bounded low tier');
for (let i = 0; i < 490; i++) g.sample(1000 / 60);
assert.equal(g.level, 'balanced', 'a normal 60Hz display can recover');
for (let i = 0; i < 490; i++) g.sample(1000 / 60);
assert.equal(g.level, 'high', 'healthy frames restore full fidelity');
for (let i = 0; i < 100; i++) g.sample(33.3);
assert.equal(g.level, 'balanced', 'failed recovery probe sheds load');
for (let i = 0; i < 500; i++) g.sample(1000 / 60);
assert.equal(g.level, 'balanced', 'failed probes back off instead of oscillating');
const resumed = new QualityGovernor('balanced');
for (let i = 0; i < 89; i++) resumed.sample(33.3);
resumed.sample(2000);
for (let i = 0; i < 89; i++) resumed.sample(33.3);
assert.equal(resumed.level, 'balanced', 'resume discards the stale timing window');
const clean = new QualityGovernor();
for (let i = 0; i < 500; i++) clean.sample(i % 60 === 0 ? 40 : 1000 / 60);
assert.equal(clean.level, 'high', 'occasional hitches do not lower quality');
for (const value of [NaN, Infinity, -1, 0]) clean.sample(value);
assert.equal(clean.level, 'high');
assert.ok(QUALITY_BUDGETS.low.pixels < QUALITY_BUDGETS.high.pixels / 3);
console.log('Quality governor: sustained load, 60Hz recovery, backoff, resume and outliers PASS');
